"""Write website-publish-list.txt: the files under website/ that should be published.

Included: *.html, site.css, site.js, root *.json, audio/*.mp3, audio/clips.json,
and every image under img/ whose file name appears in any html/json/js/css file
(website root and audio/clips.json) or in website-tools/*.py.
Excluded: scripts (*.py), .claude, unreferenced images (listed as comments at the end).

Re-run any time:  python website-tools/make_publish_list.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SITE = ROOT
OUT = os.path.join(HERE, "publish-list.txt")


def rel(p):
    return os.path.relpath(p, SITE).replace(os.sep, "/")


def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read()


def main():
    corpus_files = []
    for n in sorted(os.listdir(SITE)):
        if n.lower().endswith((".html", ".json", ".js", ".css")):
            corpus_files.append(os.path.join(SITE, n))
    clips = os.path.join(SITE, "audio", "clips.json")
    if os.path.exists(clips):
        corpus_files.append(clips)
    tools = os.path.join(ROOT, "website-tools")
    tool_files = [os.path.join(tools, n) for n in sorted(os.listdir(tools)) if n.endswith(".py")] \
        if os.path.isdir(tools) else []
    # Only site files count as "referenced by the published site". Tool scripts are
    # reported separately so a name that is only generated by a tool is visible.
    site_text = "\n".join(read(p) for p in corpus_files)
    tool_text = "\n".join(read(p) for p in tool_files)

    included, unref, tool_only = [], [], []
    for n in sorted(os.listdir(SITE)):
        p = os.path.join(SITE, n)
        if os.path.isfile(p) and n.lower().endswith((".html", ".css", ".js", ".json")):
            included.append(n)
    audio = os.path.join(SITE, "audio")
    if os.path.isdir(audio):
        for n in sorted(os.listdir(audio)):
            if n.lower().endswith((".mp3", ".json")):
                included.append("audio/" + n)
    img = os.path.join(SITE, "img")
    for dp, _dn, fns in os.walk(img):
        for n in sorted(fns):
            r = rel(os.path.join(dp, n))
            if re.search(re.escape(n), site_text):
                included.append(r)
            else:
                unref.append(r)
                if n in tool_text:
                    tool_only.append(r)
    included = sorted(set(included))
    unref = sorted(unref)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        for r in included:
            f.write(r + "\n")
        f.write("\n# EXCLUDED (not published): *.py scripts, .claude/, and unreferenced images:\n")
        for r in unref:
            f.write("# " + r + "\n")
    print("published files:", len(included))
    print("  html:", sum(r.endswith(".html") for r in included),
          " mp3:", sum(r.endswith(".mp3") for r in included),
          " img:", sum(r.startswith("img/") for r in included))
    print("unreferenced images:", len(unref))
    for r in unref:
        print("  ", r, "(named only in a tool script)" if r in tool_only else "")


if __name__ == "__main__":
    sys.exit(main())
